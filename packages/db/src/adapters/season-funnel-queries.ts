/**
 * Season behaviour analytics: how far through the Level Pass customers
 * actually get, and what that progression cost against what it earned.
 *
 * Every figure is counted from the transaction tables rather than from any
 * maintained counter, because the question these answer ("where do people
 * stop?") has to survive a counter being reset at season close. The stage
 * ladder is read from the configured checkpoints, not hardcoded, so a season
 * run with a custom ladder reports its own stages.
 */

import { and, eq, sql } from 'drizzle-orm';
import type { Database } from '../index.js';
import {
  levelPassCheckpointEvents,
  levelPassLpTransactions,
  seasons,
  vaultEntitlements,
} from '../schema.js';
import { getLevelPassCheckpoints } from './level-pass-settings.js';

export interface SeasonFunnelStage {
  checkpointLp: number;
  rewardDiamonds: number;
  /** Unique players who have crossed this checkpoint in the season. */
  reached: number;
  /** Share of all participants, 0–100. Null when there are no participants. */
  pctOfParticipants: number | null;
  /** Share of the previous stage — the drop-off between steps. Null for stage 1. */
  pctOfPrevious: number | null;
}

export interface SeasonFunnel {
  seasonId: string;
  seasonNumber: number;
  status: 'active' | 'closed';
  startsAt: Date;
  endsAt: Date;
  /** Players with at least one LP-earning order this season. */
  participants: number;
  stages: SeasonFunnelStage[];
  vaultUnlocked: number;
  totalLpAwarded: number;
  /** Contribution profit generated by participants' eligible orders. */
  profitFromParticipantsCents: number;
  /** Internal cost of rewards actually granted — pending ones have cost nothing yet. */
  rewardCostCents: number;
  retainedProfitCents: number;
  /**
   * The spec's Realized Reward Cost Ratio: reward expense / profit generated,
   * as a percentage. Designed around ~20%, but deliberately reported as
   * measured — never forced toward the target. Null when no profit yet.
   */
  realizedRewardCostRatioPct: number | null;
}

const pct = (part: number, whole: number): number | null =>
  whole > 0 ? (part / whole) * 100 : null;

export async function getSeasonFunnel(db: Database, seasonId: string): Promise<SeasonFunnel | null> {
  const [season] = await db
    .select({
      id: seasons.id,
      seasonNumber: seasons.seasonNumber,
      status: seasons.status,
      startsAt: seasons.startsAt,
      endsAt: seasons.endsAt,
    })
    .from(seasons)
    .where(eq(seasons.id, seasonId))
    .limit(1);
  if (!season) return null;

  const [participation] = await db
    .select({
      participants: sql<string>`COUNT(DISTINCT ${levelPassLpTransactions.playerProfileId})::text`,
      lpAwarded: sql<string>`COALESCE(SUM(${levelPassLpTransactions.awardedLp}), 0)::text`,
      profitCents: sql<string>`COALESCE(SUM(${levelPassLpTransactions.estimatedProfitCents}), 0)::text`,
    })
    .from(levelPassLpTransactions)
    .where(eq(levelPassLpTransactions.seasonId, seasonId));

  const reachedRows = await db
    .select({
      checkpointLp: levelPassCheckpointEvents.checkpointLp,
      reached: sql<string>`COUNT(DISTINCT ${levelPassCheckpointEvents.playerProfileId})::text`,
    })
    .from(levelPassCheckpointEvents)
    .where(eq(levelPassCheckpointEvents.seasonId, seasonId))
    .groupBy(levelPassCheckpointEvents.checkpointLp);
  const reachedByLp = new Map(reachedRows.map((r) => [r.checkpointLp, Number(r.reached)]));

  // Granted only. A reached-but-undelivered checkpoint is a liability, not an
  // expense — the same rule the financial ledger uses, which is written in the
  // same transaction as the grant.
  const [rewardCost] = await db
    .select({
      costCents: sql<string>`COALESCE(SUM(${levelPassCheckpointEvents.internalCostCents}), 0)::text`,
    })
    .from(levelPassCheckpointEvents)
    .where(
      and(
        eq(levelPassCheckpointEvents.seasonId, seasonId),
        eq(levelPassCheckpointEvents.status, 'granted'),
      ),
    );

  const [vault] = await db
    .select({ unlocked: sql<string>`COUNT(*)::text` })
    .from(vaultEntitlements)
    .where(eq(vaultEntitlements.seasonId, seasonId));

  const checkpoints = await getLevelPassCheckpoints(db);
  const participants = Number(participation?.participants ?? 0);

  let previousReached: number | null = null;
  const stages: SeasonFunnelStage[] = checkpoints.map((cp) => {
    const reached = reachedByLp.get(cp.lp) ?? 0;
    const stage: SeasonFunnelStage = {
      checkpointLp: cp.lp,
      rewardDiamonds: cp.rewardDiamonds,
      reached,
      pctOfParticipants: pct(reached, participants),
      pctOfPrevious: previousReached === null ? null : pct(reached, previousReached),
    };
    previousReached = reached;
    return stage;
  });

  const profitFromParticipantsCents = Number(participation?.profitCents ?? 0);
  const rewardCostCents = Number(rewardCost?.costCents ?? 0);

  return {
    seasonId: season.id,
    seasonNumber: season.seasonNumber,
    status: season.status,
    startsAt: season.startsAt,
    endsAt: season.endsAt,
    participants,
    stages,
    vaultUnlocked: Number(vault?.unlocked ?? 0),
    totalLpAwarded: Number(participation?.lpAwarded ?? 0),
    profitFromParticipantsCents,
    rewardCostCents,
    retainedProfitCents: profitFromParticipantsCents - rewardCostCents,
    realizedRewardCostRatioPct: pct(rewardCostCents, profitFromParticipantsCents),
  };
}

/**
 * The same figures for every season that has ever run, newest first — the
 * spec's "season comparison" report, which is what tells LevelUp whether a
 * change to the ladder actually improved progression.
 */
export async function listSeasonFunnels(db: Database): Promise<SeasonFunnel[]> {
  const rows = await db
    .select({ id: seasons.id })
    .from(seasons)
    .orderBy(sql`${seasons.seasonNumber} DESC`);

  const funnels: SeasonFunnel[] = [];
  for (const row of rows) {
    const funnel = await getSeasonFunnel(db, row.id);
    if (funnel) funnels.push(funnel);
  }
  return funnels;
}
